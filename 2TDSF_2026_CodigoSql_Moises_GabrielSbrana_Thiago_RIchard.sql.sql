    DBMS_OUTPUT.PUT_LINE('========================================');
    DBMS_OUTPUT.PUT_LINE('MEDIA DE HEALTH SCORE POR CLINICA');
    DBMS_OUTPUT.PUT_LINE('========================================');
    FOR REGISTRO IN (
        SELECT
            TB_CLINICA.NM_CLINICA AS NOME,
            COUNT(DISTINCT TB_PET.ID_PET) AS PETS,
            ROUND(AVG(TB_SCORE_HISTORICO.NR_SCORE), 2) AS MEDIA
        FROM TB_CLINICA 
        JOIN TB_PET
            ON TB_PET.ID_CLINICA = TB_CLINICA.ID_CLINICA
        JOIN TB_SCORE_HISTORICO
            ON TB_SCORE_HISTORICO.ID_PET = TB_PET.ID_PET 
        JOIN TB_TUTOR 
            ON TB_TUTOR.ID_TUTOR = TB_PET.ID_TUTOR
        GROUP BY TB_CLINICA.NM_CLINICA
        ORDER BY MEDIA DESC
    ) LOOP 
        DBMS_OUTPUT.PUT_LINE('Clinica: ' || REGISTRO.NOME);
        DBMS_OUTPUT.PUT_LINE('Quantidade de pets:' || REGISTRO.PETS);
        DBMS_OUTPUT.PUT_LINE('Média de score: ' || REGISTRO.MEDIA);
    END LOOP;
END;
