-- Executar no mesmo schema Oracle. Somente os dados criados neste teste sao
-- alterados; todos sao desfeitos pelo ROLLBACK TO. Sequences avancam normalmente.
-- O log autonomo preserva erros, caso algum teste falhe.
DECLARE
    V_TUTOR NUMBER;
    V_CLINICA NUMBER;
    V_PET NUMBER;
    V_EVENTO NUMBER;
    V_MEDICAMENTO NUMBER;
    V_TOTAL NUMBER;
    V_JSON CLOB;
    V_RELATORIO CLOB;
    V_CHAVE VARCHAR2(40) := TO_CHAR(SYSTIMESTAMP, 'YYYYMMDDHH24MISSFF6');
BEGIN
    SAVEPOINT SPRINT4_VALIDACAO;
    PKG_PETTRACK_CADASTRO.PRC_INSERT_TUTOR('Tutor validacao Sprint 4', 'sprint4_'||V_CHAVE||'@example.invalid', NULL, NULL);
    SELECT SEQ_TUTOR.CURRVAL INTO V_TUTOR FROM DUAL;
    PKG_PETTRACK_CADASTRO.PRC_INSERT_CLINICA('Clinica validacao Sprint 4', SUBSTR(V_CHAVE,1,18), NULL, NULL, NULL);
    SELECT SEQ_CLINICA.CURRVAL INTO V_CLINICA FROM DUAL;
    PKG_PETTRACK_CADASTRO.PRC_INSERT_PET('Pet validacao Sprint 4', 'Cao', 'SRD', 'M', 3, 12.345, V_TUTOR, V_CLINICA, V_PET);
    PKG_PETTRACK_CADASTRO.PRC_INSERT_EVENTO_CLINICO('CONSULTA', SYSDATE, 'Validacao', NULL, V_PET, V_CLINICA);
    SELECT SEQ_EVENTO_CLINICO.CURRVAL INTO V_EVENTO FROM DUAL;
    PKG_PETTRACK_CADASTRO.PRC_INSERT_MEDICAMENTO('Medicamento validacao', '1 dose', 'Diaria', SYSDATE, NULL, V_EVENTO);
    SELECT SEQ_MEDICAMENTO.CURRVAL INTO V_MEDICAMENTO FROM DUAL;
    PKG_PETTRACK_CADASTRO.PRC_INSERT_ADESAO_MEDICAMENTO(SYSDATE, 'S', NULL, V_MEDICAMENTO);
    PKG_PETTRACK_CADASTRO.PRC_INSERT_PROTOCOLO_PREVENTIVO('VACINA', 'Vacina validacao', NULL, SYSDATE+30, 'PENDENTE', V_PET);
    PKG_PETTRACK_CADASTRO.PRC_INSERT_NOTIFICACAO('LEMBRETE', 'Validacao Sprint 4', 'Teste transacional', 'N', V_TUTOR, V_PET);
    PKG_PETTRACK_CADASTRO.PRC_INSERT_SCORE_HISTORICO(85, 'Validacao', V_PET);
    PKG_PETTRACK_CADASTRO.PRC_INSERT_BCS_HISTORICO(5, NULL, 'Validacao', V_PET);
    PKG_PETTRACK_CADASTRO.PRC_INSERT_COLLAR_LEITURA(38, 15, 'sprint4/validacao', V_PET);
    PKG_PETTRACK_CADASTRO.PRC_INSERT_ALERTA('SEDENTARISMO', 'Validacao', 15, 'N', V_PET);
    IF PKG_PETTRACK_CONSULTA.FN_CALCULAR_TAXA_ADESAO(V_MEDICAMENTO) <> 100 THEN
        RAISE_APPLICATION_ERROR(-20901, 'Taxa de adesao incorreta.');
    END IF;
    SELECT COUNT(*) INTO V_TOTAL FROM TB_AUDITORIA_PETTRACK
    WHERE TP_OPERACAO='INSERT' AND DS_VALORES_NOVOS LIKE 'ID='||V_PET||' | Nome=Pet validacao Sprint 4%';
    IF V_TOTAL <> 1 THEN RAISE_APPLICATION_ERROR(-20902, 'Auditoria de insercao incorreta.'); END IF;
    UPDATE TB_PET SET NM_PET='Pet validacao atualizado' WHERE ID_PET=V_PET;
    SELECT COUNT(*) INTO V_TOTAL FROM TB_AUDITORIA_PETTRACK
    WHERE TP_OPERACAO='UPDATE' AND DS_VALORES_NOVOS LIKE 'ID='||V_PET||' | Nome=Pet validacao atualizado%';
    IF V_TOTAL <> 1 THEN RAISE_APPLICATION_ERROR(-20903, 'Auditoria de atualizacao incorreta.'); END IF;
    PKG_PETTRACK_CONSULTA.PRC_LISTAR_PETS_JSON(NULL, V_JSON);
    IF DBMS_LOB.INSTR(V_JSON, 'Pet validacao atualizado') = 0 THEN
        RAISE_APPLICATION_ERROR(-20904, 'Pet nao encontrado no JSON.');
    END IF;
    PKG_PETTRACK_CONSULTA.PRC_RELATORIO_SUBTOTAIS_MANUAL(V_RELATORIO);
    IF DBMS_LOB.INSTR(V_RELATORIO, 'Total Geral') = 0 THEN
        RAISE_APPLICATION_ERROR(-20905, 'Relatorio incompleto.');
    END IF;
    DBMS_LOB.FREETEMPORARY(V_JSON);
    DBMS_LOB.FREETEMPORARY(V_RELATORIO);
    ROLLBACK TO SPRINT4_VALIDACAO;
    DBMS_OUTPUT.PUT_LINE('OK: 12 cadastros empacotados, funcoes, consultas, auditoria INSERT/UPDATE e rollback.');
EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO SPRINT4_VALIDACAO;
    IF DBMS_LOB.ISTEMPORARY(V_JSON)=1 THEN DBMS_LOB.FREETEMPORARY(V_JSON); END IF;
    IF DBMS_LOB.ISTEMPORARY(V_RELATORIO)=1 THEN DBMS_LOB.FREETEMPORARY(V_RELATORIO); END IF;
    RAISE;
END;
