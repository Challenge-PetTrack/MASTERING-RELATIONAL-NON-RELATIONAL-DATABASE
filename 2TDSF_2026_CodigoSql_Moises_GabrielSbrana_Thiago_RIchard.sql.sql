-- Função 1: JSON Manual com 4 Exceções
CREATE OR REPLACE FUNCTION FN_MONTAR_JSON_PET (
    P_ID_PET     IN NUMBER,
    P_NM_PET     IN VARCHAR2,
    P_ESPECIE    IN VARCHAR2,
    P_RACA       IN VARCHAR2,
    P_PESO       IN NUMBER,
    P_NM_TUTOR   IN VARCHAR2,
    P_NM_CLINICA IN VARCHAR2
) RETURN VARCHAR2
IS
    V_JSON VARCHAR2(4000);
    
    EX_DADOS_OBRIGATORIOS EXCEPTION;
    EX_PESO_INVALIDO      EXCEPTION;
BEGIN
    IF P_ID_PET IS NULL OR P_NM_PET IS NULL OR P_NM_TUTOR IS NULL THEN
        RAISE EX_DADOS_OBRIGATORIOS;
    END IF;

    IF P_PESO IS NOT NULL AND P_PESO <= 0 THEN
        RAISE EX_PESO_INVALIDO;
    END IF;

    V_JSON := '{' ||
                '"idPet": '      || P_ID_PET || ', ' ||
                '"nome": "'      || REPLACE(P_NM_PET, '"', '\"') || '", ' ||
                '"especie": "'   || NVL(P_ESPECIE, 'N/A') || '", ' ||
                '"raca": "'      || NVL(P_RACA, 'SRD') || '", ' ||
                '"pesoKg": '     || NVL(TO_CHAR(P_PESO, 'FM999.00'), 'null') || ', ' ||
                '"tutor": "'     || REPLACE(P_NM_TUTOR, '"', '\"') || '", ' ||
                '"clinica": "'   || REPLACE(NVL(P_NM_CLINICA, 'Não associada'), '"', '\"') || '"' ||
              '}';

    RETURN V_JSON;

EXCEPTION
    WHEN EX_DADOS_OBRIGATORIOS THEN
        PRC_INSERT_LOG_ERRO('FN_MONTAR_JSON_PET', -20001, 'Erro: Identificador do Pet, Nome ou Tutor não informados.');
        RETURN '{"erro": "Dados obrigatorios ausentes"}';

    WHEN EX_PESO_INVALIDO THEN
        PRC_INSERT_LOG_ERRO('FN_MONTAR_JSON_PET', -20002, 'Erro: Peso informado menor ou igual a zero.');
        RETURN '{"erro": "Peso invalido informado"}';

    WHEN VALUE_ERROR THEN
        PRC_INSERT_LOG_ERRO('FN_MONTAR_JSON_PET', SQLCODE, 'Erro de conversao de tipos de dados.');
        RETURN '{"erro": "Erro de conversao de valor"}';

    WHEN OTHERS THEN
        PRC_INSERT_LOG_ERRO('FN_MONTAR_JSON_PET', SQLCODE, SQLERRM);
        RETURN '{"erro": "Falha inesperada ao formatar JSON"}';
END FN_MONTAR_JSON_PET;
/

-- Função 2: Taxa de Adesão com 4 Exceções
CREATE OR REPLACE FUNCTION FN_CALCULAR_TAXA_ADESAO (
    P_ID_MEDICAMENTO IN NUMBER
) RETURN NUMBER
IS
    V_TOTAL_DOSES     NUMBER := 0;
    V_DOSES_TOMADAS   NUMBER := 0;
    V_TAXA_PERCENTUAL NUMBER(5,2) := 0;
    V_EXISTE_MED      NUMBER := 0;
    
    EX_MEDICAMENTO_INEXISTENTE EXCEPTION;
    EX_SEM_DOSES_REGISTRADAS   EXCEPTION;
BEGIN
    SELECT COUNT(1) INTO V_EXISTE_MED 
    FROM TB_MEDICAMENTO 
    WHERE ID_MEDICAMENTO = P_ID_MEDICAMENTO;

    IF V_EXISTE_MED = 0 THEN
        RAISE EX_MEDICAMENTO_INEXISTENTE;
    END IF;

    SELECT 
        COUNT(1),
        COUNT(CASE WHEN ST_TOMOU = 'S' THEN 1 END)
    INTO 
        V_TOTAL_DOSES,
        V_DOSES_TOMADAS
    FROM TB_ADESAO_MEDICAMENTO
    WHERE ID_MEDICAMENTO = P_ID_MEDICAMENTO;

    IF V_TOTAL_DOSES = 0 THEN
        RAISE EX_SEM_DOSES_REGISTRADAS;
    END IF;

    V_TAXA_PERCENTUAL := ROUND((V_DOSES_TOMADAS / V_TOTAL_DOSES) * 100, 2);
    RETURN V_TAXA_PERCENTUAL;

EXCEPTION
    WHEN EX_MEDICAMENTO_INEXISTENTE THEN
        PRC_INSERT_LOG_ERRO('FN_CALCULAR_TAXA_ADESAO', -20010, 'Medicamento ID ' || P_ID_MEDICAMENTO || ' nao encontrado.');
        RETURN -1;

    WHEN EX_SEM_DOSES_REGISTRADAS THEN
        PRC_INSERT_LOG_ERRO('FN_CALCULAR_TAXA_ADESAO', -20011, 'Nenhuma dose registrada para o medicamento ID ' || P_ID_MEDICAMENTO);
        RETURN 0;

    WHEN ZERO_DIVIDE THEN
        PRC_INSERT_LOG_ERRO('FN_CALCULAR_TAXA_ADESAO', SQLCODE, 'Divisao por zero na taxa de adesao.');
        RETURN 0;

    WHEN OTHERS THEN
        PRC_INSERT_LOG_ERRO('FN_CALCULAR_TAXA_ADESAO', SQLCODE, SQLERRM);
        RETURN -99;
END FN_CALCULAR_TAXA_ADESAO;
/

-- Procedimento 1: JOIN Relacional com Saída JSON
CREATE OR REPLACE PROCEDURE PRC_LISTAR_PETS_JSON (
    P_DS_ESPECIE IN VARCHAR2 DEFAULT NULL
)
IS
    CURSOR C_PETS IS
        SELECT 
            P.ID_PET,
            P.NM_PET,
            P.DS_ESPECIE,
            P.DS_RACA,
            P.NR_PESO_KG,
            T.NM_TUTOR,
            C.NM_CLINICA
        FROM TB_PET P
        INNER JOIN TB_TUTOR T   ON T.ID_TUTOR = P.ID_TUTOR
        INNER JOIN TB_CLINICA C ON C.ID_CLINICA = P.ID_CLINICA
        WHERE (P_DS_ESPECIE IS NULL OR UPPER(P.DS_ESPECIE) = UPPER(P_DS_ESPECIE))
        ORDER BY P.ID_PET;

    V_JSON_GERADO  VARCHAR2(4000);
    V_TOTAL_LINHAS NUMBER := 0;
    
    EX_NENHUM_REGISTRO    EXCEPTION;
    EX_PARAMETRO_INVALIDO EXCEPTION;
BEGIN
    IF P_DS_ESPECIE IS NOT NULL AND LENGTH(TRIM(P_DS_ESPECIE)) < 2 THEN
        RAISE EX_PARAMETRO_INVALIDO;
    END IF;

    DBMS_OUTPUT.PUT_LINE('================================================================================');
    DBMS_OUTPUT.PUT_LINE('LISTAGEM DE PETS EM FORMATO JSON (GERAÇÃO MANUAL VIA FN_MONTAR_JSON_PET)');
    DBMS_OUTPUT.PUT_LINE('================================================================================');

    FOR REG IN C_PETS LOOP
        V_TOTAL_LINHAS := V_TOTAL_LINHAS + 1;
        
        V_JSON_GERADO := FN_MONTAR_JSON_PET(
            REG.ID_PET,
            REG.NM_PET,
            REG.DS_ESPECIE,
            REG.DS_RACA,
            REG.NR_PESO_KG,
            REG.NM_TUTOR,
            REG.NM_CLINICA
        );
        
        DBMS_OUTPUT.PUT_LINE(V_JSON_GERADO);
    END LOOP;

    IF V_TOTAL_LINHAS = 0 THEN
        RAISE EX_NENHUM_REGISTRO;
    END IF;

    DBMS_OUTPUT.PUT_LINE('--------------------------------------------------------------------------------');
    DBMS_OUTPUT.PUT_LINE('Total de registros processados: ' || V_TOTAL_LINHAS);

EXCEPTION
    WHEN EX_PARAMETRO_INVALIDO THEN
        PRC_INSERT_LOG_ERRO('PRC_LISTAR_PETS_JSON', -20020, 'Filtro de espécie inválido ou muito curto.');
        DBMS_OUTPUT.PUT_LINE('[EXCEÇÃO TRATADA]: Filtro de espécie fornecido é inválido.');

    WHEN EX_NENHUM_REGISTRO THEN
        PRC_INSERT_LOG_ERRO('PRC_LISTAR_PETS_JSON', -20021, 'Nenhum pet encontrado para os critérios informados.');
        DBMS_OUTPUT.PUT_LINE('[EXCEÇÃO TRATADA]: Nenhum registro encontrado na consulta.');

    WHEN NO_DATA_FOUND THEN
        PRC_INSERT_LOG_ERRO('PRC_LISTAR_PETS_JSON', SQLCODE, 'Dados não encontrados.');
        DBMS_OUTPUT.PUT_LINE('[EXCEÇÃO TRATADA]: Sem dados disponíveis.');

    WHEN OTHERS THEN
        PRC_INSERT_LOG_ERRO('PRC_LISTAR_PETS_JSON', SQLCODE, SQLERRM);
        DBMS_OUTPUT.PUT_LINE('[EXCEÇÃO TRATADA]: Erro inesperado: ' || SQLERRM);
END PRC_LISTAR_PETS_JSON;
