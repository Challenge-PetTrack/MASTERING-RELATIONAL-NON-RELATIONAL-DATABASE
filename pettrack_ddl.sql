-- BLOCO LAG/LEAD - Evolucao do Health Score por Pet

BEGIN
    DBMS_OUTPUT.PUT_LINE('========================================');
    DBMS_OUTPUT.PUT_LINE('EVOLUCAO DO HEALTH SCORE POR PET');
    DBMS_OUTPUT.PUT_LINE('========================================');
    FOR REGISTRO IN (
        SELECT
            TB_PET.NM_PET AS PET,
            TB_SCORE_HISTORICO.NR_SCORE AS SCORE_ATUAL,
            
            NVL(TO_CHAR(LAG(TB_SCORE_HISTORICO.NR_SCORE)
                OVER (
                PARTITION BY TB_SCORE_HISTORICO.ID_PET
                      ORDER BY TB_SCORE_HISTORICO.DT_REGISTRO)),'Vazio')  AS SCORE_ANTERIOR,
                      
            NVL(TO_CHAR(LEAD(TB_SCORE_HISTORICO.NR_SCORE)
                OVER (
                PARTITION BY TB_SCORE_HISTORICO.ID_PET 
                ORDER BY TB_SCORE_HISTORICO.DT_REGISTRO)), 'Vazio') AS PROXIMO_SCORE
        FROM TB_PET
        JOIN TB_SCORE_HISTORICO
            ON TB_SCORE_HISTORICO.ID_PET = TB_PET.ID_PET
        ORDER BY TB_PET.NM_PET
    ) LOOP
        DBMS_OUTPUT.PUT_LINE('Pet: ' || REGISTRO.PET || ' | Anterior: ' || REGISTRO.SCORE_ANTERIOR|| ' | Atual: ' || REGISTRO.SCORE_ATUAL || ' | Proximo: ' || REGISTRO.PROXIMO_SCORE);
    END LOOP;
END;
