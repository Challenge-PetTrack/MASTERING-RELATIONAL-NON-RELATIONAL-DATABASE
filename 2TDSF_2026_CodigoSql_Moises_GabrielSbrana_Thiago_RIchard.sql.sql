-- BLOCO 5: Cursor Explícito com Sumarização
DECLARE
    CURSOR C_EXIBE IS
        SELECT 
            TB_SCORE_HISTORICO.NR_SCORE AS NOTA,
            TB_PET.NM_PET AS PET
        FROM TB_SCORE_HISTORICO
        JOIN TB_PET
            ON TB_PET.ID_PET = TB_SCORE_HISTORICO.ID_PET
        ORDER BY TB_PET.NM_PET;
        
    V_MENOR_40    NUMBER := 0;
    V_ENTRE_40_70 NUMBER := 0;
    V_MAIOR_70    NUMBER := 0;
