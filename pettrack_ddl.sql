-- BLOCO 4 CURSOR  

DECLARE
    CURSOR C_EXIBE IS
        SELECT 
            TB_SCORE_HISTORICO.NR_SCORE AS NOTA,
            TB_PET.NM_PET AS PET
        FROM TB_SCORE_HISTORICO
        JOIN TB_PET
            ON TB_PET.ID_PET = TB_SCORE_HISTORICO.ID_PET
        ORDER BY TB_PET.NM_PET;
        V_MENOR_40  NUMBER :=0 ;
        V_ENTRE_40_70 NUMBER:=0;
        V_MAIOR_70 NUMBER:=0;
BEGIN
    FOR V_EXIBE IN C_EXIBE LOOP
         DBMS_OUTPUT.PUT_LINE('Resgistros de score de pets: ' ||
         'Pet: ' || V_EXIBE.PET || '  | SCORE: ' || V_EXIBE.NOTA );
         IF V_EXIBE.NOTA < 40 THEN
            V_MENOR_40 := V_MENOR_40+1;
        ELSIF V_EXIBE.NOTA >= 40 AND V_EXIBE.NOTA < 70 THEN
             V_ENTRE_40_70 := V_ENTRE_40_70+1;
        ELSE
            V_MAIOR_70 := V_MAIOR_70+1;
        END IF;
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('===========================================');
    DBMS_OUTPUT.PUT_LINE('SUMARIZACAO:');
    DBMS_OUTPUT.PUT_LINE('Score < 40    : ' || V_MENOR_40);
    DBMS_OUTPUT.PUT_LINE('Score 40 a 70 : ' || V_ENTRE_40_70);
    DBMS_OUTPUT.PUT_LINE('Score > 70    : ' || V_MAIOR_70);
END;
