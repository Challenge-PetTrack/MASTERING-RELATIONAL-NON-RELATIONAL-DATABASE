BEGIN
    DBMS_OUTPUT.PUT_LINE('========================================');
    DBMS_OUTPUT.PUT_LINE('MEDIA DE HEALTH SCORE POR CLINICA');
    DBMS_OUTPUT.PUT_LINE('========================================');
    FOR REGISTRO IN (
        SELECT
        TB_CLINICA.NM_CLINICA AS NOME,
        COUNT(DISTINCT TB_PET.ID_PET) AS PETS,
        ROUND(AVG(TB_SCORE_HISTORICO.NR_SCORE), 2) AS MEDIA
        FROM TB_CLINICA 
        JOIN TB_PET
            ON TB_PET.ID_CLINICA = TB_CLINICA.ID_CLINICA
        JOIN TB_SCORE_HISTORICO
            ON TB_SCORE_HISTORICO.ID_PET = TB_PET.ID_PET 
        JOIN TB_TUTOR 
            ON TB_TUTOR.ID_TUTOR = TB_PET.ID_TUTOR
        GROUP BY TB_CLINICA.NM_CLINICA
        ORDER BY MEDIA DESC
    )LOOP 
        DBMS_OUTPUT.PUT_LINE('Clinica: ' || REGISTRO.NOME);
        DBMS_OUTPUT.PUT_LINE('Quantidade de pets:' || REGISTRO.PETS);
        DBMS_OUTPUT.PUT_LINE('Média de score: ' || REGISTRO.MEDIA);
    END LOOP;
END;
/

BEGIN
    DBMS_OUTPUT.PUT_LINE('========================================');
    DBMS_OUTPUT.PUT_LINE('ALERTAS POR TIPO NOS ULTIMOS 30 DIAS');
    DBMS_OUTPUT.PUT_LINE('========================================');
    FOR REGISTRO IN (
        SELECT
            TB_ALERTA.TP_ALERTA                AS TIPO,
            TB_PET.NM_PET                      AS PET,
            TB_TUTOR.NM_TUTOR                  AS TUTOR,
            COUNT(TB_ALERTA.ID_ALERTA)         AS QT_ALERTAS
        FROM TB_ALERTA
        JOIN TB_PET
            ON TB_PET.ID_PET = TB_ALERTA.ID_PET
        JOIN TB_TUTOR
            ON TB_TUTOR.ID_TUTOR = TB_PET.ID_TUTOR
        JOIN TB_CLINICA
            ON TB_CLINICA.ID_CLINICA = TB_PET.ID_CLINICA
        WHERE TB_ALERTA.DT_ALERTA >= SYSDATE - 30
        GROUP BY TB_ALERTA.TP_ALERTA, TB_PET.NM_PET, TB_TUTOR.NM_TUTOR
        ORDER BY QT_ALERTAS DESC
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(
            'Tipo: '      || REGISTRO.TIPO      ||
            ' | Pet: '    || REGISTRO.PET       ||
            ' | Tutor: '  || REGISTRO.TUTOR     ||
            ' | Qtd: '    || REGISTRO.QT_ALERTAS
        );
    END LOOP;
END;
/

BEGIN
    DBMS_OUTPUT.PUT_LINE('========================================');
    DBMS_OUTPUT.PUT_LINE('ADESAO MEDICAMENTOSA POR TUTOR');
    DBMS_OUTPUT.PUT_LINE('========================================');
    FOR REGISTRO IN (
        SELECT
            TB_TUTOR.NM_TUTOR AS TUTOR,
            TB_PET.NM_PET AS PET,
            TB_MEDICAMENTO.NM_MEDICAMENTO AS MEDICAMENTO,
            TB_ADESAO_MEDICAMENTO.ST_TOMOU AS TOMOU
        FROM TB_TUTOR 
        JOIN TB_PET 
            ON TB_PET.ID_TUTOR = TB_TUTOR.ID_TUTOR
        JOIN TB_EVENTO_CLINICO
            ON TB_EVENTO_CLINICO.ID_PET = TB_PET.ID_PET
        JOIN TB_MEDICAMENTO 
            ON TB_MEDICAMENTO.ID_EVENTO = TB_EVENTO_CLINICO.ID_EVENTO
        JOIN TB_ADESAO_MEDICAMENTO 
            ON TB_ADESAO_MEDICAMENTO.ID_MEDICAMENTO = TB_MEDICAMENTO.ID_MEDICAMENTO
        GROUP BY TB_TUTOR.NM_TUTOR, TB_PET.NM_PET, TB_MEDICAMENTO.NM_MEDICAMENTO,TB_ADESAO_MEDICAMENTO.ST_TOMOU
        ORDER BY TB_TUTOR.NM_TUTOR, TB_PET.NM_PET
    ) LOOP
        DBMS_OUTPUT.PUT_LINE('Tutor: '       || REGISTRO.TUTOR);
        DBMS_OUTPUT.PUT_LINE('Pet: '         || REGISTRO.PET);
        DBMS_OUTPUT.PUT_LINE('Medicamento: ' || REGISTRO.MEDICAMENTO);
        DBMS_OUTPUT.PUT_LINE('Tomou: '       || REGISTRO.TOMOU);
    END LOOP;
