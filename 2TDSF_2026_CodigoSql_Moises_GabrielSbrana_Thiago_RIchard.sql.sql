-- Procedimento 2: Relatório com Subtotais e Total Geral
CREATE OR REPLACE PROCEDURE PRC_RELATORIO_SUBTOTAIS_MANUAL
IS
    CURSOR C_FATOS IS
        SELECT 
            C.NM_CLINICA AS CATEGORIA_1,
            P.NM_PET     AS CATEGORIA_2,
            NVL(CL.NR_ATIVIDADE, 0) AS VALOR_NUMERICO
        FROM TB_COLLAR_LEITURA CL
        INNER JOIN TB_PET P     ON P.ID_PET = CL.ID_PET
        INNER JOIN TB_CLINICA C ON C.ID_CLINICA = P.ID_CLINICA
        ORDER BY C.NM_CLINICA, P.NM_PET;

    V_CAT1_ANTERIOR   TB_CLINICA.NM_CLINICA%TYPE := NULL;
    V_SUBTOTAL_CAT1   NUMBER(12,2) := 0;
    V_TOTAL_GERAL     NUMBER(12,2) := 0;
    V_TOTAL_LINHAS    NUMBER := 0;
    V_PRIMEIRA_LINHA  BOOLEAN := TRUE;

    EX_SEM_DADOS_FATOS EXCEPTION;
    EX_VALOR_NEGATIVO  EXCEPTION;
BEGIN
    DBMS_OUTPUT.PUT_LINE(RPAD('Clinica', 35) || ' ' || RPAD('Pet', 20) || ' ' || LPAD('Atividade', 12));
    DBMS_OUTPUT.PUT_LINE(RPAD('-', 35, '-') || ' ' || RPAD('-', 20, '-') || ' ' || LPAD('-', 12, '-'));

    FOR REG IN C_FATOS LOOP
        V_TOTAL_LINHAS := V_TOTAL_LINHAS + 1;

        IF REG.VALOR_NUMERICO < 0 THEN
            RAISE EX_VALOR_NEGATIVO;
        END IF;

        IF NOT V_PRIMEIRA_LINHA AND REG.CATEGORIA_1 <> V_CAT1_ANTERIOR THEN
            DBMS_OUTPUT.PUT_LINE(RPAD('Sub Total', 56) || ' ' || LPAD(TO_CHAR(V_SUBTOTAL_CAT1, 'FM999990.00'), 12));
            V_SUBTOTAL_CAT1 := 0;
        END IF;

        DBMS_OUTPUT.PUT_LINE(
            RPAD(REG.CATEGORIA_1, 35) || ' ' ||
            RPAD(REG.CATEGORIA_2, 20) || ' ' ||
            LPAD(TO_CHAR(REG.VALOR_NUMERICO, 'FM999990.00'), 12)
        );

        V_SUBTOTAL_CAT1 := V_SUBTOTAL_CAT1 + REG.VALOR_NUMERICO;
        V_TOTAL_GERAL   := V_TOTAL_GERAL + REG.VALOR_NUMERICO;
        V_CAT1_ANTERIOR := REG.CATEGORIA_1;
        V_PRIMEIRA_LINHA := FALSE;
    END LOOP;

    IF V_TOTAL_LINHAS = 0 THEN
        RAISE EX_SEM_DADOS_FATOS;
    END IF;

    DBMS_OUTPUT.PUT_LINE(RPAD('Sub Total', 56) || ' ' || LPAD(TO_CHAR(V_SUBTOTAL_CAT1, 'FM999990.00'), 12));
    DBMS_OUTPUT.PUT_LINE(RPAD('Total Geral', 56) || ' ' || LPAD(TO_CHAR(V_TOTAL_GERAL, 'FM999990.00'), 12));

EXCEPTION
    WHEN EX_SEM_DADOS_FATOS THEN
        PRC_INSERT_LOG_ERRO('PRC_RELATORIO_SUBTOTAIS_MANUAL', -20030, 'Sem dados para sumarização.');
        DBMS_OUTPUT.PUT_LINE('[EXCEÇÃO TRATADA]: Não há registros suficientes.');

    WHEN EX_VALOR_NEGATIVO THEN
        PRC_INSERT_LOG_ERRO('PRC_RELATORIO_SUBTOTAIS_MANUAL', -20031, 'Valor numérico inconsistente.');
        DBMS_OUTPUT.PUT_LINE('[EXCEÇÃO TRATADA]: Valor numérico inválido encontrado.');

    WHEN VALUE_ERROR THEN
        PRC_INSERT_LOG_ERRO('PRC_RELATORIO_SUBTOTAIS_MANUAL', SQLCODE, 'Erro de conversão numérica.');
